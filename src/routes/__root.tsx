function RootShell({ children }: { children: React.ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      <AuthProvider>
        <AuthGate />
      </AuthProvider>
      <Toaster position="bottom-right" richColors />
    </QueryClientProvider>
  );
}

/** Redirects unauthenticated users to /login; authenticated users away from /login */
function AuthGate() {
  const { user, loading } = useAuth();
  const location = useLocation();
  const router = useRouter();
  const onLogin = location.pathname === "/login";

  useEffect(() => {
    if (loading) return;
    if (!user && !onLogin) {
      router.navigate({ to: "/login", replace: true });
    }
    if (user && onLogin) {
      const dest = user.role === "admin" ? "pmewa" : (user.workspaceId ?? "pmewa");
      router.navigate({ to: "/$workspace", params: { workspace: dest }, replace: true });
    }
  }, [user, loading, onLogin, router]);

  if (loading) {
    return (
      <div className="flex min-h-screen items-center justify-center bg-background">
        <div className="h-8 w-8 animate-spin rounded-full border-2 border-border border-t-primary" />
      </div>
    );
  }

  if (!user && !onLogin) return null;

  return (
    <NotificationsProvider>
      <Outlet />
      <OnboardingModal />
    </NotificationsProvider>
  );
}
